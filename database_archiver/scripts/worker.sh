#!/bin/bash

# -------------------------------------------------------------------------
# Система логической архивации баз данных
# -------------------------------------------------------------------------
# Сценарий выполняет полную выгрузку базы данных MariaDB, обеспечивает
# её сжатие и автоматическую ротацию старых копий для оптимизации хранилища.

set -e

# Подготовка временных меток и путей
CURRENT_TIMESTAMP="$(date '+%Y%m%d_%H%M%S')"
FILE_NAME="${DATABASE_ARCHIVE_PREFIX}_${CURRENT_TIMESTAMP}.sql.gz"
FILE_PATH="${ARTIFACTS_PATH}/${FILE_NAME}"


# -------------------------------------------------------------------------
# Служба протоколирования (логи)
# -------------------------------------------------------------------------

record_log_entry() {
    printf '[%s] %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$1"
}


# -------------------------------------------------------------------------
# Управление жизненным циклом архивов (ротация)
# -------------------------------------------------------------------------

purge_obsolete_archives() {
    record_log_entry "Запуск очистки архивов старше ${RETENTION_PERIOD_DAYS:-30} дней"

    find "$ARTIFACTS_PATH" \
        -type f \
        -name "${DATABASE_ARCHIVE_PREFIX}_*.sql.gz" \
        -mtime +"${RETENTION_PERIOD_DAYS:-30}" \
        -delete
}


# -------------------------------------------------------------------------
# Основной процесс выгрузки данных
# -------------------------------------------------------------------------

record_log_entry "Начало процедуры архивации базы данных"

# Передача пароля в среду выполнения для авторизации утилиты
export MYSQL_PWD="${DATABASE_PASSWORD}"

# Выгрузка данных с сохранением процедур и триггеров
mysqldump \
    --host="$DATABASE_HOST" \
    --user="$DATABASE_USER" \
    --single-transaction \
    --routines \
    --triggers \
    "$DATABASE_SCHEMA" | gzip > "$FILE_PATH"

record_log_entry "Архив успешно создан: $FILE_PATH"

# Запуск ротации для удаления устаревших копий
purge_obsolete_archives

record_log_entry "Процедура архивации полностью завершена"
