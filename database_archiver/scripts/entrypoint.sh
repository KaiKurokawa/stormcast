#!/bin/bash

# -------------------------------------------------------------------------
# Точка входа сервиса архивации: формирование расписания
# -------------------------------------------------------------------------
# Сценарий подготавливает среду выполнения для планировщика задач.
# Он считывает интервал запуска из настроек и регистрирует задачу
# в системной таблице выполнения.

set -e

CRON_FILE="/etc/crontab"
SCHEDULE="${CRON_SCHEDULE:-0 3 * * *}"

echo "[АРХИВАТОР] Инициализация службы резервного копирования..."


# -------------------------------------------------------------------------
# Регистрация задачи
# -------------------------------------------------------------------------
# Формирование строки расписания, где заданный интервал связан с воркером.
# По умолчанию запуск установлен на 03:00 ночи.

echo "$SCHEDULE /usr/local/bin/worker.sh" > "$CRON_FILE"
echo "[АРХИВАТОР] Установлено расписание: $SCHEDULE"


# -------------------------------------------------------------------------
# Активация планировщика
# -------------------------------------------------------------------------

echo "[АРХИВАТОР] Запуск планировщика Supercronic..."
exec /usr/local/bin/supercronic "$CRON_FILE"
