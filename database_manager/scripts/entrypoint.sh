#!/bin/sh
set -e

# Выполнение предварительной настройки (генерация файлов, установка прав)
# Скрипт выполняется от имени root, что позволяет корректно изменять 
# владельца файлов внутри именованного тома Docker.
/usr/local/bin/bootstrap.sh

# Передача управления оригинальному скрипту инициализации pgAdmin.
# Команда su понижает привилегии до пользователя pgadmin (UID 5050), 
# обеспечивая безопасность запуска основного процесса.
exec su pgadmin -s /bin/sh -c "/entrypoint.sh $*"
