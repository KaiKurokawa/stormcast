"""
Общие утилиты логирования.

Этот модуль определяет базовую настройку логирования и утилиты 
контекстного логирования, используемые во всем проекте. 
Он обеспечивает структурированное, учитывающее этапы и богатое контекстом 
логирование как для бизнес-логики, так и для технических слоев.

Экспортирует:
    - setup_logging:
        Инициализирует конфигурацию логирования с опциональным форматированием в JSON.

    - add_local_context, replace_local_context:
        Добавляет или заменяет кратковременный контекст для одной операции, 
        генерирующей логи (например, внутри функции, метода или блока `log_stage`).

    - add_bound_context, replace_bound_context:
        Добавляет или заменяет временный потоконезависимый (thread-local) контекст, 
        который сохраняется при множественных вложенных вызовах или работе декораторов 
        в рамках одной логической операции. Несмотря на название, этот контекст не является 
        постоянным или глобальным — его необходимо явно очищать после использования.

    - with_log_context:
        Декоратор, внедряющий контекстную информацию на время выполнения функции.

    - log_stage:
        Контекстный менеджер для логирования этапов выполнения, поддерживающий 
        автоматическое отслеживание продолжительности и структурированные метаданные этапа.

Стратегия контекстного логирования:
    - Локальный контекст (Временный):
        Эфемерный и ограниченный рамками одной функции или блока кода.
        Должен использоваться с оператором `with`.
        Автоматически очищается при выходе из блока.

    - Связанный контекст (Потоконезависимый, Временный):
        Существует на протяжении множественных вызовов функций в рамках одной 
        логической операции (например, выполнения задачи или запуска оркестратора). 
        Также предназначен для использования с `with`.
        Должен быть явно очищен или заменен во избежание утечек.

Примечание:
    Все функции контекстного логирования предоставляют временный контекст.
    Их необходимо использовать через `with` или в качестве декораторов 
    (например, `@with_log_context`), чтобы гарантировать предсказуемый 
    жизненный цикл и избежать случайного сохранения состояния.
"""

