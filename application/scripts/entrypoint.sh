#!/bin/bash

# -------------------------------------------------------------------------
# Точка входа приложения
# -------------------------------------------------------------------------
# Сценарий выполняет подготовку окружения перед запуском основного процесса.
# Включает проверку доступности базы данных, применение миграций
# и создание администратора по умолчанию.

set -e


# -------------------------------------------------------------------------
# Служба протоколирования
# -------------------------------------------------------------------------

record_log_entry() {
    printf '[%s] %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$1"
}


# -------------------------------------------------------------------------
# Проверка готовности базы данных
# -------------------------------------------------------------------------

record_log_entry "Ожидание готовности базы данных..."

# Цикл ожидания, пока порт базы данных не станет доступен
# (Имена переменных синхронизированы с settings.py)
while ! python -c "import socket; s=socket.socket(); s.settimeout(1); s.connect(('${DATABASE_INTERFACE_HOST:-database}', ${DATABASE_INTERFACE_CONTAINER_PORT:-5432}))" 2>/dev/null; do
    record_log_entry "База данных недоступна, повторная попытка через 2 секунды..."
    sleep 2
done

record_log_entry "База данных готова к работе"


# -------------------------------------------------------------------------
# Применение миграций и подготовка статики
# -------------------------------------------------------------------------

record_log_entry "Применение миграций базы данных"
python manage.py migrate --noinput

record_log_entry "Сборка статических файлов"
python manage.py collectstatic --noinput


# -------------------------------------------------------------------------
# Создание администратора по умолчанию
# -------------------------------------------------------------------------
# Инициализация суперпользователя на основе переменных окружения.
# Если пользователь с таким логином уже существует, создание пропускается.

if [ -n "${APPLICATION_DEFAULT_USER:-}" ] && [ -n "${APPLICATION_DEFAULT_PASSWORD:-}" ]; then
    record_log_entry "Проверка и создание администратора по умолчанию..."

    python manage.py shell -c "
import os
from django.contrib.auth import get_user_model

User = get_user_model()

username = os.environ.get('APPLICATION_DEFAULT_USER')
password = os.environ.get('APPLICATION_DEFAULT_PASSWORD')
email = os.environ.get('APPLICATION_DEFAULT_EMAIL', 'admin@stormcast.local')

# Определяем поле для логина (username или email, если модель кастомная)
username_field = getattr(User, 'USERNAME_FIELD', 'username')

if username and password:
    if not User.objects.filter(**{username_field: username}).exists():
        User.objects.create_superuser(**{username_field: username}, email=email, password=password)
        print('[ENTRYPOINT] Администратор успешно создан.')
    else:
        print('[ENTRYPOINT] Администратор уже существует, пропуск.')
"
else
    record_log_entry "Переменные для администратора не заданы, пропуск создания."
fi


# -------------------------------------------------------------------------
# Запуск целевого процесса
# -------------------------------------------------------------------------
# Передача управления команде, указанной при запуске контейнера (CMD).
# Это может быть Gunicorn для веб-сервера или Celery для фоновых задач.

record_log_entry "Передача управления процессу: $@"
exec "$@"
